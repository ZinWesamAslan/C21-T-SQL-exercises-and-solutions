-- 2. السكربت المطور بالربط مع تاريخ بدء الشعبة (StartDate)
WITH NumberedSessions AS (
    -- توليد 15 جلسة متتالية لكل شعبة
    SELECT 1 AS SessionNum
    UNION ALL
    SELECT SessionNum + 1 FROM NumberedSessions WHERE SessionNum < 15
)
INSERT INTO Attendance (EnrollmentID, SessionDate, Status, Remarks, CreatedByUserID)
SELECT 
    e.EnrollmentID,
    -- تاريخ الجلسة = تاريخ بداية الشعبة + (رقم الجلسة * 3 أيام)
    DATEADD(DAY, (n.SessionNum * 3), cb.StartDate) AS SessionDate,
    
    -- توزيع الحالات بشكل منطقي وواقعي
    CASE (e.EnrollmentID + n.SessionNum) % 10
        WHEN 0 THEN 'Absent'
        WHEN 1 THEN 'Late'
        WHEN 2 THEN 'Excused'
        WHEN 3 THEN 'Late'
        ELSE 'Present'
    END AS Status,
    
    -- ملاحظات الحضور
    CASE (e.EnrollmentID + n.SessionNum) % 10
        WHEN 0 THEN 'Unexcused absence'
        WHEN 1 THEN 'Traffic delay'
        WHEN 2 THEN 'Medical leave'
        WHEN 3 THEN 'Overslept'
        ELSE 'Attended on time'
    END AS Remarks,
    
    3 AS CreatedByUserID
FROM 
    Enrollments e
    INNER JOIN CourseBatches cb ON e.BatchID = cb.BatchID
